package com.javafundmentals;

public class Datatypes {
	Integer Student;
	String Sname;
	Integer Age;
	Double Marks;
	Character Grade;
	Boolean Passed;
	public static void main(String[] args) {
		Datatypes c=new Datatypes();
		c.Student=101;
		c.Sname="chandu";
		c.Age=22;
		c.Marks=90.00;
		c.Grade='A';
		c.Passed=true;
		System.out.println("student:"+c.Student);
		System.out.println("sname:"+c.Sname);
		System.out.println("age:"+c.Age);
		System.out.println("marks:"+c.Marks);
		System.out.println("grade:"+c.Grade);
		System.out.println("passed:"+c.Passed);
		
		

	}

}

